CREATE DATABASE IF NOT EXISTS CONFIG_DB;
CREATE SCHEMA IF NOT EXISTS CONFIG_DB.ENV;

-- Création du stage privé (chiffré par Snowflake)
CREATE OR REPLACE STAGE CONFIG_DB.ENV.STAGE_CONFIG
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

CREATE FILE FORMAT IF NOT EXISTS FF_CSV
TYPE = CSV

CREATE FILE FORMAT IF NOT EXISTS FF_JSON
TYPE = JSON

CREATE FILE FORMAT IF NOT EXISTS FF_PARQUET
TYPE = PARQUET 

CREATE STAGE my_s3_stage
  STORAGE_INTEGRATION = s3_int
  URL = 's3://tpcdsnicolasstage'